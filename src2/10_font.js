const GLYPHS = {};
(function parseFont(){
  for (const line of FONT_SRC.split('\n')) {
    if (!line.length) continue;
    const ch = line[0], top = +line[1];
    if (isNaN(top)) continue;
    const rows = line.slice(2).split('/');
    const pix = []; let w = 0;
    for (let y = 0; y < rows.length; y++) {
      for (let x = 0; x < rows[y].length; x++) {
        if (rows[y][x] === '#') { pix.push([x, top + y]); if (x + 1 > w) w = x + 1; }
      }
    }
    GLYPHS[ch] = { w: w || 3, pix };
  }
})();

const FONT_H = 9;                 // alto de linea
const _atlas = {};                // cache de atlas por color

function glyphAtlas(color) {
  if (_atlas[color]) return _atlas[color];
  const keys = Object.keys(GLYPHS);
  const cv = document.createElement('canvas');
  cv.width = keys.length * 8; cv.height = 8;
  const c = cv.getContext('2d');
  c.fillStyle = color;
  const pos = {};
  keys.forEach((k, i) => {
    pos[k] = i * 8;
    for (const [x, y] of GLYPHS[k].pix) c.fillRect(i * 8 + x, y, 1, 1);
  });
  return (_atlas[color] = { cv, pos });
}

function textWidth(s) {
  let w = 0;
  for (const ch of s) { const g = GLYPHS[ch] || GLYPHS['?']; w += g.w + 1; }
  return w > 0 ? w - 1 : 0;
}

// dibuja texto pixel-perfect
function drawText(c, s, x, y, color) {
  const a = glyphAtlas(color || '#101018');
  let cx = x | 0;
  for (const ch of s) {
    const g = GLYPHS[ch] || GLYPHS['?'];
    const p = a.pos[ch] !== undefined ? a.pos[ch] : a.pos['?'];
    c.drawImage(a.cv, p, 0, 8, 8, cx, y | 0, 8, 8);
    cx += g.w + 1;
  }
  return cx;
}

// parte un texto en lineas que entren en `maxw` pixeles
function wrapText(s, maxw) {
  const out = [];
  for (const para of String(s).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (textWidth(t) > maxw && line) { out.push(line); line = word; }
      else line = t;
    }
    out.push(line);
  }
  return out;
}
